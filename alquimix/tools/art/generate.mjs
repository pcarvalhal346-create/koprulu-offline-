// Alquimix — generates every PNG used by the game, the Defold .atlas files and the Lumi rig.
// Usage: cd tools/art && npm install && node generate.mjs
import fs from 'node:fs';
import path from 'node:path';
import { render, svg, decode, encode, bbox, crop, write, ROOT } from './lib.mjs';
import * as P from './pieces.mjs';
import * as B from './board.mjs';
import * as U from './ui.mjs';
import { fx } from './fx.mjs';
import * as L from './lumi.mjs';
import * as BG from './backgrounds.mjs';

const atlases = {};
function add(atlas, rel, svgText) {
  write(rel, render(svgText));
  (atlases[atlas] ||= []).push(rel);
}

// pieces -----------------------------------------------------------------
for (const id of P.BASE_IDS) {
  add('pieces', `assets/elements/${id}.png`, P.basePiece(id));
  add('pieces', `assets/elements/${id}_charged.png`, P.chargedPiece(id));
}
for (const id of P.COMPOUND_IDS) add('pieces', `assets/compounds/${id}.png`, P.compoundPiece(id));

// board ------------------------------------------------------------------
const boardArt = {
  tile_light: B.tile(true), tile_dark: B.tile(false), board_frame: B.boardFrame(),
  rock: B.rock(), rock_hard: B.rockHard(), rock_hard_cracked: B.rockHardCracked(),
  frost_1: B.frost(1), frost_2: B.frost(2), vine: B.vine(), corruption: B.corruption(),
  portal_in: B.portal(false), portal_out: B.portal(true), conveyor: B.conveyor(),
  select_ring: B.selectRing(), hint_glow: B.hintGlow(), partner_ring: B.partnerRing(), aura: B.aura(),
};
for (const [k, v] of Object.entries(boardArt)) add('board', `assets/board/${k}.png`, v);

// ui ---------------------------------------------------------------------
const uiArt = {
  panel: U.panel(), panel_dark: U.panelDark(), bubble: U.bubble(),
  btn_primary: U.button('primary'), btn_secondary: U.button('secondary'), btn_danger: U.button('danger'), btn_green: U.button('green'),
  btn_round: U.roundButton('secondary'), btn_round_gold: U.roundButton('primary'),
  star_full: U.starFull(), star_empty: U.starEmpty(),
  node_locked: U.mapNode('locked'), node_open: U.mapNode('open'), node_done: U.mapNode('done'), node_glow: U.nodeGlow(),
  path_dot: U.pathDot(), ribbon: U.ribbon(), card_known: U.card(true), card_unknown: U.card(false),
  hand: U.hand(), white: U.white(), soft_circle: U.softCircle(), round_rect: U.roundRect(), goal_slot: U.goalSlot(),
  logo: U.logo(),
  hud_bar: U.hudBar(), moves_badge: U.movesBadge(), pill: U.pill(), bottom_bar: U.bottomBar(),
  nav_tab_on: U.navTab(true), nav_tab_off: U.navTab(false),
};
for (const [k, v] of Object.entries(uiArt)) add('ui', `assets/ui/${k}.png`, v);
for (const [k, f] of Object.entries(U.icons)) add('ui', `assets/ui/icon_${k}.png`, f());

// effects ----------------------------------------------------------------
for (const [k, f] of Object.entries(fx)) add('fx', `assets/effects/fx_${k}.png`, f());

// backgrounds --------------------------------------------------------------
add('bg', 'assets/backgrounds/bg_menu.png', BG.menu());
add('bg', 'assets/backgrounds/bg_world1.png', BG.world1());
add('bg', 'assets/backgrounds/bg_world2.png', BG.world2());
add('bg', 'assets/backgrounds/bg_world3.png', BG.world3());

// Lumi rig -----------------------------------------------------------------
const { w: CW, h: CH } = L.CANVAS;
const rig = { parts: [], joints: {} };
function cropPart(id, body) {
  const png = decode(render(svg(CW, CH, body, L.DEFS)));
  const b = bbox(png);
  const c = crop(png, b, 2);
  const rel = `assets/lumi/${id}.png`;
  write(rel, encode(c.png));
  (atlases.lumi ||= []).push(rel);
  return { cx: (c.x0 + c.x1) / 2, cy: (c.y0 + c.y1) / 2, w: c.x1 - c.x0, h: c.y1 - c.y0 };
}
for (const part of L.PARTS) {
  rig.joints[part.joint] = { x: part.pivot[0], y: part.pivot[1] };
  if (part.variants) {
    const variants = {};
    for (const [vid, body] of Object.entries(part.variants)) variants[vid] = cropPart(`lumi_${vid}`, body);
    rig.parts.push({ id: part.id, joint: part.joint, face: part.face, variants });
  } else {
    rig.parts.push({ id: part.id, joint: part.joint, ...cropPart(part.id, part.body) });
  }
}
const lua = (v, ind = '') => {
  if (typeof v === 'number') return Number.isInteger(v) ? String(v) : v.toFixed(1);
  if (typeof v === 'string') return JSON.stringify(v);
  if (Array.isArray(v)) return '{\n' + v.map((x) => ind + '\t' + lua(x, ind + '\t')).join(',\n') + '\n' + ind + '}';
  return '{ ' + Object.entries(v).map(([k, x]) => `${k} = ${lua(x, ind + '\t')}`).join(', ') + ' }';
};
fs.writeFileSync(path.join(ROOT, 'data/lumi_rig.lua'),
  '-- Generated by tools/art/generate.mjs. Do not edit by hand.\n' +
  '-- Coordinates are in the 400x520 drawing canvas (y down); gui/lumi_view.lua converts them.\n' +
  `return {\n\tcanvas = { w = ${CW}, h = ${CH} },\n\tjoints = ${lua(rig.joints, '\t')},\n\tparts = ${lua(rig.parts, '\t')},\n}\n`);

// app icon (Lumi portrait on a medallion) -----------------------------------
const icon = svg(512, 512,
  `<rect width="512" height="512" rx="110" fill="url(#ibg)"/>` +
  `<g transform="translate(56 30) scale(1.0)">${L.portraitBody('eyes_happy', 'mouth_grin')}</g>`,
  L.DEFS + `<linearGradient id="ibg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#6553D9"/><stop offset="1" stop-color="#15224E"/></linearGradient>`);
write('assets/icons/icon_512.png', render(icon));

// atlases --------------------------------------------------------------------
for (const [name, files] of Object.entries(atlases)) {
  const body = files.map((f) => `images {\n  image: "/${f}"\n  sprite_trim_mode: SPRITE_TRIM_MODE_OFF\n}\n`).join('') +
    `margin: 2\nextrude_borders: 2\ninner_padding: 0\n`;
  fs.writeFileSync(path.join(ROOT, `assets/atlases/${name}.atlas`), body);
}
